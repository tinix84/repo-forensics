from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path


def evidence_lines(evidence: list[dict]) -> list[str]:
    return [json.dumps(e, ensure_ascii=False, sort_keys=True) for e in evidence]


def digest(lines: list[str]) -> str:
    """Content digest of the evidence set. Evidence ids are sequential, hence only meaningful
    together with this digest: any change to the evidence (tool version, signatures, code) changes it."""
    h = hashlib.sha256()
    for ln in lines:
        h.update(ln.encode("utf-8") + b"\n")
    return "sha256:" + h.hexdigest()[:32]


def _mid(i: int) -> str:
    return f"c{i}"


def mermaid(report: dict) -> str:
    comps = report["components"]["items"]
    ids = {c["name"]: _mid(i) for i, c in enumerate(comps)}
    cyc = {m for cy in report["components"]["cycles"] for m in cy}
    lines = ["%% Generated by repo-forensics. Component = directory-based grouping (see report.json).",
             f"%% commit: {report['provenance'].get('commit_sha')}",
             "graph TD"]
    for c in comps:
        label = c["name"].replace('"', "'")
        extra = []
        if c["entrypoints"]:
            extra.append("entry: " + ", ".join(sorted(set(c["entrypoints"]))))
        sub = f"<br/><small>{c['code_lines']} LOC" + (f"; {'; '.join(extra)}" if extra else "") + "</small>"
        lines.append(f'    {ids[c["name"]]}["{label}{sub}"]')
    for c in comps:
        for dst, n in c["depends_on"].items():
            if dst in ids:
                lines.append(f"    {ids[c['name']]} -->|{n}| {ids[dst]}")
    lines.append("    classDef entry stroke-width:3px;")
    lines.append("    classDef cycle stroke-dasharray: 5 5;")
    for c in comps:
        if c["entrypoints"]:
            lines.append(f"    class {ids[c['name']]} entry;")
        if c["name"] in cyc:
            lines.append(f"    class {ids[c['name']]} cycle;")
    return "\n".join(lines) + "\n"


def _table(headers: list[str], rows: list[list]) -> str:
    def cell(x):
        return re.sub(r"\|", "\\|", "" if x is None else str(x))
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    out += ["| " + " | ".join(cell(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def markdown(report: dict) -> str:
    p, f = report["provenance"], report["fingerprint"]
    mg, deps, tests = report["module_graph"], report["dependencies"], report["tests"]
    cx = report["complexity"]
    s = []
    s.append("# Repository forensics report\n")
    s.append(f"- **Repository:** {p.get('url') or '(local)'}\n- **Commit:** `{p.get('commit_sha')}`"
             f"{' (dirty working tree)' if p.get('dirty') else ''}\n- **Analyzed:** {p['analyzed_at']}"
             f"\n- **Evidence digest:** `{report.get('evidence_digest')}`"
             f"\n- **License (heuristic):** {p.get('license')}\n- **Tool:** repo-forensics {report['tool']['version']}, "
             f"tier {report['tool']['tier']}\n")
    s.append("> Measurements are facts. Architecture is an inference. Every row below links to an evidence id "
             "in `evidence.jsonl`. Status: CONFIRMED / SUPPORTED / INFERRED / UNKNOWN.\n")
    s.append("## 1. Fingerprint\n")
    rows = [[k, v["files"], v["source_code_lines"], f"{v['source_share']:.1%}" if v["source_share"] is not None else "",
             f["analysis_coverage"].get(k, "")]
            for k, v in f["languages"].items() if v["kind"] == "programming"]
    s.append(_table(["Language", "Files", "Production code lines", "Share", "Analysis"], rows) + "\n")
    s.append(f"Build systems: {', '.join(f['build_systems']) or 'none'} · Package roots: {len(f['package_roots'])} · "
             f"CI: {len(f['ci'])} workflow(s) · File classes: {f['file_classes']}\n")
    s.append("## 2. Entry points\n")
    s.append(_table(["Type", "Name", "Module", "Detection", "Status", "Evidence"],
                    [[e["type"], e.get("name") or "", e.get("module") or "", e["detection"], e["status"], e["evidence_id"]]
                     for e in report["entrypoints"]]) + "\n" if report["entrypoints"] else "_None found._\n")
    if report["repo_shape"]["hypothesis"]:
        s.append(f"Repository shape (INFERRED): **{', '.join(report['repo_shape']['hypothesis'])}** "
                 f"({report['repo_shape']['evidence_id']})\n")
    s.append("## 3. Components (directory-based)\n")
    s.append(f"Method: `{report['components']['method']}`\n")
    s.append(_table(["Component", "Modules", "LOC", "Depth", "Depends on", "Used by", "Tests import it", "Signals", "Evidence"],
                    [[c["name"], c["modules"], c["code_lines"], c["dependency_depth"], len(c["depends_on"]),
                      len(c["depended_on_by"]), c["imported_by_tests"], ", ".join(c["signals"][:5]), c["evidence_id"]]
                     for c in report["components"]["items"]]) + "\n")
    s.append("_Depth_ = longest dependency chain to a component that depends on nothing internal (0 = bottom layer).\n")
    s.append("See `architecture.mmd` for the component graph.\n")
    s.append("## 4. Module graph\n")
    s.append(f"{mg['production_modules']} production modules, {mg['edges']} edges. Fan-in {mg['fan_in']}; "
             f"fan-out {mg['fan_out']}.\n")
    hubs = ", ".join(f"{h['module']} ({h['fan_in']})" for h in mg["hubs"]) or "none"
    s.append(f"- Import cycles: **{len(mg['cycles'])}** (of which at import time: {len(mg['import_time_cycles'])})\n"
             f"- Hubs (high fan-in): {hubs}\n"
             f"- Orphans: {len(mg['orphans'])}\n")
    s.append("## 5. Computational primitives, storage, boundaries\n")
    order = ["CALLED", "IMPORTED", "DECLARED", "NON_PRODUCTION_ONLY"]
    sig = sorted(report["signals"], key=lambda x: (x["category"], order.index(x["usage_level"])))
    s.append(_table(["Category", "Library", "Primitive", "Usage", "Refined", "Reachable", "Evidence"],
                    [[x["category"], x["library"], x["primitive"], x["usage_level"],
                      ", ".join(x["refined_primitives"]) or "", x["reachable_from_entrypoint"], x["evidence_id"]]
                     for x in sig]) + "\n" if sig else "_No signatures matched._\n")
    s.append("Usage levels: DECLARED (manifest) < IMPORTED < CALLED (production code). "
             "CENTRAL is decided in the inference step.\n")
    s.append(f"## 6. AI fingerprint\n\nStatus: **{report['ai']['status']}** · classification: {report['ai']['classification']}\n")
    s.append(f"{report['ai']['note']}\n")
    s.append("## 7. Dependencies\n")
    s.append(f"Declared: {deps['declared_counts']} · Third-party packages imported: {len(deps['third_party_imported'])}\n")
    if deps["imported_not_declared"]:
        s.append(f"- Imported but not declared: {', '.join(deps['imported_not_declared'])}\n")
    if deps["declared_not_imported"]:
        s.append(f"- Declared (runtime) but not imported: {', '.join(deps['declared_not_imported'])}\n")
    s.append("## 8. Complexity\n")
    if cx["status"] == "measured":
        s.append(f"{cx['functions']} functions · CC {cx['cyclomatic']} · " +
                 " · ".join(f"{k}: {v}" for k, v in cx.items() if k.startswith("functions_cc_gt")) + "\n")
        s.append(_table(["Function", "File:line", "CC", "NLOC"],
                        [[h["function"], f"{h['file']}:{h['line']}", h["cc"], h["nloc"]] for h in cx["hotspots"]]) + "\n")
    else:
        s.append("_Not measured._\n")
    s.append("## 9. Tests (static inventory)\n")
    fws = ", ".join(tests["frameworks"]) or "none detected"
    untested = ", ".join(tests["components_not_imported_by_tests"]) or "none"
    s.append(f"{tests['test_modules']} test modules, {tests['test_functions']} test functions, "
             f"test/production LOC ratio {tests['test_to_production_ratio']}, frameworks: {fws}.\n"
             f"Components not imported by any test: {untested}\n")
    s.append("## 10. Signals (not verdicts)\n")
    s.append(_table(["Rule", "Target", "Detail", "Severity", "Evidence"],
                    [[x["rule"], x["target"], x["detail"], x["severity"], x["evidence_id"]] for x in report["smells"]]) + "\n"
             if report["smells"] else "_None._\n")
    s.append("## 11. Unknowns\n")
    s.append("\n".join(f"- **{u['question']}** — {u['reason']} ({u['evidence_id']})" for u in report["unknowns"]) + "\n")
    s.append("## 12. Checklist\n")
    s.append(_table(["Gate", "Status", "Note"], [[c["gate"], c["status"], c["note"]] for c in report["checklist"]]) + "\n")
    s.append(f"\nEvidence by status: {report['evidence_summary']}\n")
    return "\n".join(s)


def write_outputs(report: dict, evidence: list[dict], out_dir: Path) -> None:
    out_dir = Path(out_dir)
    (out_dir / "metrics").mkdir(parents=True, exist_ok=True)
    graph = report.pop("_graph", {})
    funcs = report.pop("_functions", [])
    lines = evidence_lines(evidence)
    report["evidence_digest"] = digest(lines)
    (out_dir / "report.json").write_text(json.dumps(report, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    with (out_dir / "evidence.jsonl").open("w", encoding="utf-8") as fh:
        for ln in lines:
            fh.write(ln + "\n")
    (out_dir / "dependency-graph.json").write_text(json.dumps(graph, indent=1) + "\n", encoding="utf-8")
    (out_dir / "metrics" / "languages.json").write_text(
        json.dumps(report["fingerprint"]["languages"], indent=2) + "\n", encoding="utf-8")
    (out_dir / "metrics" / "complexity.json").write_text(json.dumps(funcs, indent=1) + "\n", encoding="utf-8")
    (out_dir / "architecture.mmd").write_text(mermaid(report), encoding="utf-8")
    (out_dir / "report.md").write_text(markdown(report), encoding="utf-8")
    from .html import render_html
    render_html(out_dir)
